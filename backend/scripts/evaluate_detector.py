"""Measure the trained detector per class on the test set and write the results to docs/model_evaluation.md.

Run inside the backend container, after `scripts.train_detector`:
    docker compose run --rm --no-deps web python -m scripts.evaluate_detector [--model storage/models/detector.pt]

For every class: mAP@50, mAP@50-95, precision and recall on storage/yolo/test, plus how many instances
it had in train and test, since the classes that perform worst are usually the ones with the least data.
The report is regenerated on every run, so run it again after training a new model. A hand-written
"## Notes" section at the end of the report is kept.
"""
import argparse
from collections import Counter
from datetime import date
from pathlib import Path

from ultralytics import YOLO

from vision.products import PRODUCTS

BACKEND_DIR = Path(__file__).resolve().parent.parent
YOLO_DIR = BACKEND_DIR / "storage" / "yolo"
# Ultralytics resolves a relative data.yaml path against its own datasets directory, so it must be absolute
DATA_YAML = YOLO_DIR / "data.yaml"
REPORT = BACKEND_DIR / "docs" / "model_evaluation.md"
# A class below this mAP@50 is listed as performing poorly
WEAK_MAP50 = 0.5
NOTES_HEADING = "## Notes"


def count_instances(split: str) -> tuple[Counter, int]:
    """Instances per class id in a split, and the number of images in it."""
    labels = list((YOLO_DIR / split / "labels").glob("*.txt"))
    counts = Counter(
        int(line.split()[0])
        for label in labels
        for line in label.read_text(encoding="utf-8").splitlines()
        if line.strip()
    )
    return counts, len(labels)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", type=Path, default=BACKEND_DIR / "storage" / "models" / "detector.pt")
    parser.add_argument("--device", default="cpu")
    args = parser.parse_args()

    metrics = YOLO(str(args.model)).val(data=str(DATA_YAML), split="test", device=args.device,
                                        plots=False, verbose=False, project="/tmp/evaluate_detector")
    train_counts, train_images = count_instances("train")
    test_counts, test_images = count_instances("test")

    # class_result(i) is indexed by position in ap_class_index, which only holds the classes in the test set
    rows = []
    for position, class_id in enumerate(metrics.ap_class_index):
        precision, recall, map50, map50_95 = metrics.class_result(position)
        rows.append((PRODUCTS[class_id].name, map50, map50_95, precision, recall,
                     test_counts[class_id], train_counts[class_id]))
    rows.sort(key=lambda row: row[1])
    weak = [row for row in rows if row[1] < WEAK_MAP50]
    not_tested = [product.name for class_id, product in enumerate(PRODUCTS) if test_counts[class_id] == 0]

    precision, recall, map50, map50_95 = metrics.mean_results()
    lines = [
        "# Detector evaluation",
        "",
        f"Generated by `scripts/evaluate_detector.py` on {date.today():%d/%m/%Y}.",
        "",
        f"- Model: `{args.model.relative_to(BACKEND_DIR) if args.model.is_relative_to(BACKEND_DIR) else args.model}`",
        f"- Test set: {test_images} images, {sum(test_counts.values())} instances "
        f"(training set: {train_images} images, {sum(train_counts.values())} instances)",
        "",
        "## Overall",
        "",
        "| mAP@50 | mAP@50-95 | Precision | Recall |",
        "|---|---|---|---|",
        f"| {map50:.3f} | {map50_95:.3f} | {precision:.3f} | {recall:.3f} |",
        "",
        "## Per class",
        "",
        "Sorted from worst to best mAP@50.",
        "",
        "| Class | mAP@50 | mAP@50-95 | Precision | Recall | Test instances | Train instances |",
        "|---|---|---|---|---|---|---|",
        *(f"| {name} | {m50:.3f} | {m95:.3f} | {p:.3f} | {r:.3f} | {n_test} | {n_train} |"
          for name, m50, m95, p, r, n_test, n_train in rows),
        "",
        "## Worst classes",
        "",
    ]
    if weak:
        lines += [f"Classes with mAP@50 below {WEAK_MAP50}:", ""]
        lines += [f"- **{name}**: mAP@50 {m50:.3f}, recall {r:.3f}, {n_train} training instances"
                  for name, m50, _, _, r, _, n_train in weak]
    else:
        lines.append(f"No class has mAP@50 below {WEAK_MAP50}.")
    if not_tested:
        lines += ["", f"Not in the test set, so not measured: {', '.join(not_tested)}."]
    lines.append("")

    # Keep the analysis written by hand from the previous report
    previous = REPORT.read_text(encoding="utf-8") if REPORT.exists() else ""
    if NOTES_HEADING in previous:
        lines.append(previous[previous.index(NOTES_HEADING):].rstrip() + "\n")

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    print(f"Saved the report to {REPORT.relative_to(BACKEND_DIR)}")


if __name__ == "__main__":
    main()
